// Integration test in the repository's disposable Zotero profile, with a fake ACP agent.
// No real library, account, model API, or business documents are used.
async function main(ctx) {
  const { Zotero, IOUtils, PathUtils, win } = ctx;
  const check = (v, message) => { if (!v) throw new Error(message); };
  const key = "extensions.zotero-chat.settings";
  Zotero.Prefs.set(key, JSON.stringify({ backend: "codex", welcomed: true, translateTo: "zh-Hans", translateModel: { codex: "gpt-6-luna" } }), true);
  await ctx.resize(1280, 900);
  const pdfPath = PathUtils.join(Zotero.Profile.dir, "bilingual-fixture.pdf");
  const objs = []; const add = body => { objs.push(body); return objs.length; };
  const catalog = add(""), tree = add(""), font = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  const kids = Array.from({ length: 20 }, (_, index) => {
    const text = `BT /F1 12 Tf 72 720 Td 18 TL (Section ${index + 1}. The method controls information flow in an agent.) Tj T* (The paper distinguishes trusted instructions from untrusted observations.) Tj T* (This paragraph is generated locally for the bilingual reader test.) Tj ET`;
    const content = add(`<< /Length ${text.length} >>\nstream\n${text}\nendstream`);
    return add(`<< /Type /Page /Parent ${tree} 0 R /MediaBox [0 0 612 792] /Contents ${content} 0 R /Resources << /Font << /F1 ${font} 0 R >> >> >>`);
  });
  objs[catalog - 1] = `<< /Type /Catalog /Pages ${tree} 0 R >>`;
  objs[tree - 1] = `<< /Type /Pages /Kids [${kids.map(k => k + " 0 R").join(" ")}] /Count ${kids.length} >>`;
  let pdf = "%PDF-1.4\n"; const offsets = objs.map((body, i) => { const start = pdf.length; pdf += `${i + 1} 0 obj\n${body}\nendobj\n`; return start; });
  const xref = pdf.length;
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offsets.map(n => String(n).padStart(10, "0") + " 00000 n \n").join("");
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root ${catalog} 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  await IOUtils.writeUTF8(pdfPath, pdf);
  const att = await Zotero.Attachments.importFromFile({ file: Zotero.File.pathToFile(pdfPath), libraryID: Zotero.Libraries.userLibraryID });
  const sourcePath = await att.getFilePathAsync();
  const sourceBytes = await IOUtils.read(sourcePath);
  await Zotero.Reader.open(att.id);
  const reader = await ctx.waitFor(() => Zotero.Reader._readers.find(r => r.itemID === att.id && r._internalReader?._primaryView), "PDF reader");
  const raw = reader._internalReader.wrappedJSObject ?? reader._internalReader;
  await raw._setReadingMode(true, true);
  const native = raw._primarySDTView.wrappedJSObject ?? raw._primarySDTView;
  await ctx.waitFor(() => native._iframe?.contentDocument?.querySelectorAll("#sdt-content p[data-ref-path]").length > 2, "native paragraphs");
  const nativeDoc = native._iframe.contentDocument;
  const paragraphs = [...nativeDoc.querySelectorAll("#sdt-content p[data-ref-path]")];
  const target = paragraphs[1];
  const span = target.querySelector("[data-text-index]");
  const range = nativeDoc.createRange(); range.selectNodeContents(span);
  let annotation = { ...native.getAnnotationFromRange(range, "highlight", "#a3e36d"), id: "TESTANNO", comment: "Layout regression fixture" };
  check(annotation.position, "source annotation missing");
  const storedPosition = JSON.stringify(annotation.position);
  native.setAnnotations(reader._iframeWindow.wrappedJSObject.JSON.parse(JSON.stringify([annotation]))); annotation = native._annotations[0]; native._handleViewUpdate(true);
  const topBefore = range.getBoundingClientRect().top;
  // Capture popup updates without creating a real library annotation.
  const popupRects = [];
  const popupHandler = native._options.onSetAnnotationPopup;
  native._options.onSetAnnotationPopup = data => { if (data?.rect) popupRects.push(data.rect); };
  native._annotationPopup = reader._iframeWindow.wrappedJSObject.JSON.parse(JSON.stringify({ annotation }));
  const manager = ctx.plugin.bilingual();
  await manager.toggle(reader);
  check(manager.status().active, "bilingual reader did not start");
  const view = raw._primarySDTView.wrappedJSObject ?? raw._primarySDTView;
  const doc = view._iframe.contentDocument;
  await ctx.waitFor(() => manager.status().done > 0 || manager.status().failed > 0, "a visible paragraph finishes", 25000);
  check(manager.status().failed === 0, "translation failed: " + doc.querySelector(".zmc-bi-note")?.textContent);
  const model = manager.status().model;
  check(model === "gpt-6-luna", "wrong model: " + model);
  await ctx.sleep(1200);
  const before = manager.status();
  check(before.done < before.total, "offscreen paragraphs were translated");
  check(doc.querySelector(".zmc-bi-slot[data-state=done] .zmc-bi-text")?.textContent, "no inline translation");
  check(doc.querySelector(".zmc-bi-slot[data-state=done]").previousElementSibling.hasAttribute("data-ref-path"), "translation is not directly after its original");
  const cacheDir = PathUtils.join(Zotero.Profile.dir, "zotero-chat", "bilingual-cache");
  const files = (await IOUtils.getChildren(cacheDir)).filter(path => path.endsWith(`/${att.libraryID}-${att.key}.json`)); check(files.length === 1, "cache was not persisted");
  const cache = JSON.parse(await IOUtils.readUTF8(files[0])); check(cache.entries.length > 0, "cache is empty");
  check(cache.entries.every(([key]) => JSON.parse(key)[2] === "gpt-6-luna"), "cache has wrong model identity");
  const group = native._annotationRenderRootEl.querySelector('g[data-annotation-id="TESTANNO"]');
  check(group, "annotation overlay missing after translation");
  const sourceRect = native.toDisplayedRange(annotation.position).getBoundingClientRect();
  const overlayRect = group.getBoundingClientRect();
  const delta = Math.abs(sourceRect.top - overlayRect.top);
  check(sourceRect.top - topBefore > 10, "fixture did not move the annotated paragraph");
  check(delta < 2, "annotation overlay is displaced by " + delta);
  check(JSON.stringify(annotation.position) === storedPosition, "source annotation coordinates changed");
  check(popupRects.length > 0, "annotation popup was not repositioned");
  const popupExpected = native._clientRectToViewportRect(sourceRect);
  check(Math.abs(popupRects.at(-1)[1] - popupExpected.top) < 2, "popup is displaced");
  const translationStyle = nativeDoc.defaultView.getComputedStyle(nativeDoc.querySelector('.zmc-bi-slot[data-state=done]'));
  const lightInk = translationStyle.color;
  check(translationStyle.color !== nativeDoc.defaultView.getComputedStyle(target).color, "translation color is not distinct");
  await ctx.snapshot("bilingual-annotation-aligned");
  native._annotationPopup = null; native._options.onSetAnnotationPopup = popupHandler;
  const slot = nativeDoc.querySelector('.zmc-bi-slot[data-state=done]');
  const body = slot.querySelector('.zmc-bi-text');
  const savedText = body.textContent;
  const fold = [...slot.querySelectorAll('button')].find(b => b.textContent === '收起译文');
  fold.click(); await ctx.sleep(100);
  check(body.hidden && fold.textContent === '展开译文', "collapse did not retain an expand button");
  let foldedRect = native._annotationRenderRootEl.querySelector('g[data-annotation-id="TESTANNO"]').getBoundingClientRect();
  check(Math.abs(foldedRect.top - native.toDisplayedRange(annotation.position).getBoundingClientRect().top) < 2, "annotation displaced after collapse");
  fold.click(); await ctx.sleep(100);
  check(!body.hidden && body.textContent === savedText, "expand lost the cached result");
  const cachedSlot = nativeDoc.querySelector('.zmc-bi-slot[data-state=done] .zmc-bi-note');
  const refreshButton = slot.querySelector('button');
  refreshButton.click();
  await ctx.waitFor(() => slot.dataset.state === 'done' && slot.querySelector('.zmc-bi-note').textContent === '译文 · 已保存到本地', "explicit retranslation finishes", 15000);
  check(manager.status().failed === 0, "retranslation failed");
  nativeDoc.documentElement.style.colorScheme = "dark";
  const darkInk = nativeDoc.defaultView.getComputedStyle(slot).color;
  check(darkInk !== lightInk, "dark theme did not change translation ink");
  await ctx.snapshot("bilingual-dark-colors");
  nativeDoc.documentElement.style.removeProperty("color-scheme");
  await manager.toggle(reader);
  check(raw._primarySDTView, "pre-existing native reading mode was closed");
  const restored = native._annotationRenderRootEl.querySelector('g[data-annotation-id="TESTANNO"]').getBoundingClientRect();
  check(Math.abs(restored.top - native.toDisplayedRange(annotation.position).getBoundingClientRect().top) < 2, "annotation displaced after removing translations");
  await manager.dispose(); ctx.plugin.bilingualReader = null;
  const restarted = ctx.plugin.bilingual();
  await restarted.toggle(reader);
  await ctx.waitFor(() => restarted.status().cached > 0, "persistent cache hit after rebuilding the manager", 20000);
  await ctx.sleep(800);
  const after = restarted.status();
  check(after.sessionsStarted === 0, "a cache-only reading started a model session: " + JSON.stringify(after));
  await ctx.snapshot("bilingual-cached-pass");
  await restarted.toggle(reader);
  const finalBytes = await IOUtils.read(sourcePath);
  check(finalBytes.length === sourceBytes.length && finalBytes.every((b, i) => b === sourceBytes[i]), "the original PDF was modified");
  return { annotationDelta: delta, sourcePositionUnchanged: true, popupRepositioned: true, collapseExpand: true, explicitRetranslation: true, darkColors: true, before, after, cacheEntries: cache.entries.length, model, originalUnmodified: true };
}
